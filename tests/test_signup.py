def test_signup_with_html_characters_in_email_stores_verbatim(client):
    """Email containing HTML characters must be stored verbatim so the
    frontend is responsible for escaping before rendering in innerHTML."""
    # Arrange
    activity_name = "Chess Club"
    email = '<script>alert(1)</script>@test.edu'

    # Act
    response = client.post(f"/activities/{activity_name}/signup", params={"email": email})

    # Assert - the API accepts the email as-is (escaping is a frontend concern)
    assert response.status_code == 200

    activities_response = client.get("/activities")
    participants = activities_response.json()[activity_name]["participants"]
    assert email in participants


def test_unregister_removes_participant_from_activity(client):
    # Arrange
    activity_name = "Chess Club"
    email = "daniel@mergington.edu"

    # Act
    response = client.delete(f"/activities/{activity_name}/signup", params={"email": email})

    # Assert
    assert response.status_code == 200
    assert response.json() == {"message": f"Removed {email} from {activity_name}"}

    activities_response = client.get("/activities")
    participants = activities_response.json()[activity_name]["participants"]
    assert email not in participants


